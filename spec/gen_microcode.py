#!/usr/bin/env python3
"""Generate the field tables of the KS10 microword from the ITS microcode.

The ITS KS10 microcode sources (src/kshack/ of the submodule 3rdparty/its)
are the first source of truth (AGENTS.md). This program assembles them
with spec/micro.py, as the ITS build does with MICRO, and writes from the
assembly:

  - The fields of the microword (the definitions "NAME/=<first:last>" in
    .UCODE mode). The bits have the numbers of MICRO: bit 0 is the left
    end of the 108-bit word (ks10, ".WIDTH/108"). A name has the first 19
    characters of the source name, as in MICRO (TOK3).
  - The fields of the dispatch ROM word (the definitions in .DCODE mode).
  - The layout of the RAM file (ks10, ".RAMFILE"), which the 8080 loads
    into the control RAM. MICRO packs the listed items from left to right
    into 108 bits (micro, $RAMFL and RAMFL4). A number "n/0" or "0" is n
    or 1 bits of padding. "ODD PARITY<a:b,...>" is one bit: the XOR of the
    given bits of the RAM file entry; "EVEN PARITY" is its complement
    (micro, RAMFP1 and PNTB91).
  - The words of the control RAM and the dispatch ROM, and the symbols.

Output (paths relative to the repository root):
  emu/ks10-core-uop/src/fields.rs
  emu/ks10-core-uop/src/ucode.rs

Usage: gen_microcode.py --its DIR [--check] [--root DIR]
  --its DIR  the ITS tree (the submodule 3rdparty/its).
  --check    compare the output with the file on disk; write nothing.

Exit status 1 if a check fails. Only the Python standard library is used.
"""

import argparse
import re
import sys
from pathlib import Path

import its_sources as its
import micro

OUT_RS = "emu/ks10-core-uop/src/fields.rs"
OUT_UCODE = "emu/ks10-core-uop/src/ucode.rs"
HEADER = "Generated by spec/gen_microcode.py from the ITS microcode sources. Do not edit."
WIDTH = 108

class MicrocodeError(Exception):
    """The sources do not have the expected form."""


def fields(a: micro.Assembler, ram: int) -> list:
    """[(name, first, last, "file:line")] of the fields of the microword
    (micro.UCODE) or of the dispatch ROM word (micro.DISP), in the order of
    the source. The names are those of MICRO: the first 19 characters."""
    out = []
    f = a.fields
    while f is not None:
        if f.ram == ram and f.source is not None:
            out.append((f.line, f.name, f.pos - f.size + 1, f.pos, f.source))
        f = f.next_field
    return [x[1:] for x in sorted(out)]


def ramfile_items(a: micro.Assembler) -> list:
    """The items of the RAM file, from left to right.

    Each item is ("field", name, first, width, dest), ("pad", width, dest)
    or ("parity", odd, ((first, last), ...), dest). dest is the first bit
    of the item in the RAM file entry; first is a microword bit.
    """
    width = a.ramfile_words * 36
    if width != WIDTH:
        raise MicrocodeError(f".RAMFILE: {width} bits, expected {WIDTH}")
    by_bits = {(first, last - first + 1): name for name, first, last, _ in fields(a, micro.UCODE)}
    items = []
    for first, size, dest in a.ramfile_fields:
        name = by_bits.get((first, size))
        if name is None:
            raise MicrocodeError(f".RAMFILE: bits {first} to {first + size - 1} are not one field")
        items.append(("field", name, first, size, dest))
    parity = {}
    for dest, first, count, complement in a.ramfile_parity:
        # RAMFP1: the complement goes with the first range of a bit.
        odd, ranges = parity.setdefault(dest, (not complement, []))
        ranges.append((first, first + count - 1))
    items += [("parity", odd, tuple(r), dest) for dest, (odd, r) in parity.items()]
    items.sort(key=lambda i: i[-1])
    out, bit = [], 0
    for item in items:
        dest = item[-1]
        if dest > bit:
            out.append(("pad", dest - bit, bit))
        out.append(item)
        bit = dest + (item[3] if item[0] == "field" else 1)
    if bit < WIDTH:
        out.append(("pad", WIDTH - bit, bit))
    return out


def rs_ident(name: str) -> str:
    s = name.upper().replace("#", "_NUM_")
    s = re.sub(r"[^A-Z0-9]+", "_", s).strip("_")
    return s


def render_rust(a: micro.Assembler) -> str:
    items = ramfile_items(a)
    out = [f"// {HEADER}", "",
           "//! The fields of the KS10 microword and of the dispatch ROM word, and the",
           "//! layout of the RAM file, from the ITS microcode sources",
           "//! **[microcode]** (`ks10`, `.WIDTH`, `.RAMFILE` and the field definitions).",
           "//! Bit 0 is the left end of a word, as in MICRO.", "",
           "/// A field: bits `first..=last` of a word, bit 0 at the left end.",
           "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
           "pub struct Field {",
           "    pub name: &'static str,",
           "    pub first: u8,",
           "    pub last: u8,",
           "}", "",
           "/// The width of a microword in bits (`.WIDTH/108`).",
           f"pub const WIDTH: u32 = {WIDTH};", ""]
    for kind, ram, doc in (("u", micro.UCODE, "microword"), ("d", micro.DISP, "dispatch ROM word")):
        idents = {}
        out.append(f"/// The fields of the {doc}.")
        out.append(f"pub mod {kind} {{")
        out.append("    use super::Field;")
        defs = fields(a, ram)
        for name, first, last, where in defs:
            ident = rs_ident(name)
            if ident in idents:
                raise MicrocodeError(f"fields {name!r} and {idents[ident]!r} have the same Rust name")
            idents[ident] = name
            out.append(f"    /// `{name}/=<{first}:{last}>` ({where}).")
            out.append(f"    pub const {ident}: Field = Field {{ name: \"{name}\", first: {first}, last: {last} }};")
        out.append("    /// All fields, in the order of the source.")
        out.append("    pub const ALL: &[Field] = &[")
        for name, *_ in defs:
            out.append(f"        {rs_ident(name)},")
        out.append("    ];")
        out.append("}")
        out.append("")
    out += ["/// An item of the RAM file entry, which is 108 bits in three 36-bit words.",
            "/// `dest` is the first bit of the item in the entry, bit 0 at the left end of",
            "/// the first word.",
            "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
            "pub enum RamItem {",
            "    /// A microword field.",
            "    Field { field: Field, dest: u8 },",
            "    /// Bits that are 0.",
            "    Pad { width: u8, dest: u8 },",
            "    /// One parity bit: the XOR of the entry bits in `ranges` (`odd`), or its",
            "    /// complement (`!odd`, \"EVEN PARITY\").",
            "    Parity { odd: bool, ranges: &'static [(u8, u8)], dest: u8 },",
            "}", "",
            f"/// The items of `.RAMFILE` ({a.ramfile_source}), from left to right.",
            "pub const RAMFILE: &[RamItem] = &["]
    for item in items:
        if item[0] == "field":
            _, name, _, _, dest = item
            out.append(f"    RamItem::Field {{ field: u::{rs_ident(name)}, dest: {dest} }},")
        elif item[0] == "pad":
            out.append(f"    RamItem::Pad {{ width: {item[1]}, dest: {item[2]} }},")
        else:
            ranges = ", ".join(f"({a}, {b})" for a, b in item[2])
            odd = "true" if item[1] else "false"
            out.append(f"    RamItem::Parity {{ odd: {odd}, ranges: &[{ranges}], dest: {item[3]} }},")
    out.append("];")
    out.append("")
    return "\n".join(out)


def rs_str(s: str) -> str:
    if any(c in s for c in '"\\') or not s.isascii() or not s.isprintable():
        raise MicrocodeError(f"symbol {s!r} needs an escape")
    return f'"{s}"'


def render_ucode(a: micro.Assembler) -> str:
    """The words and the symbols of the assembly."""
    if sorted(a.drom) != list(range(micro.MAXDSP)):
        raise MicrocodeError("the dispatch ROM is not complete")
    out = [f"// {HEADER}", "",
           "//! The microcode of the ITS build, assembled from the ITS microcode sources",
           "//! by spec/micro.py as MICRO assembles `KSHACK; MCR 262` **[microcode]**",
           "//! (`micro`; the ITS build, `build/ks10/processor.tcl`).", "",
           "/// The control RAM words: the address and the 108-bit word, bit 0 at the",
           "/// left end. The other addresses have no word.",
           "pub const CRAM: &[(u16, u128)] = &["]
    for pc in sorted(a.cram):
        out.append(f"    (0o{pc:04o}, 0o{a.cram[pc]:036o}),")
    out += ["];", "",
            "/// The dispatch ROM words by opcode, 36 bits each.",
            f"pub const DROM: [u64; {micro.MAXDSP}] = ["]
    for k in range(0, micro.MAXDSP, 4):
        out.append("    " + " ".join(f"0o{a.drom[pc]:012o}," for pc in range(k, k + 4)))
    out += ["];", "",
            "/// A symbol of a field: a value, or the address of a tag (field `J`).",
            "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
            "pub struct Symbol {",
            "    /// A field of the dispatch ROM word (`.DCODE`), not of the microword.",
            "    pub dcode: bool,",
            "    pub field: &'static str,",
            "    pub name: &'static str,",
            "    pub value: u32,",
            "}", "",
            "/// The symbols of the fields, without the macros, in the order of MICRO.",
            "pub const SYMBOLS: &[Symbol] = &["]
    for f, syms in a.field_list():
        if f.name == "MACRO%":
            continue
        dcode = "true" if f.ram == micro.DISP else "false"
        for s in syms:
            out.append(f"    Symbol {{ dcode: {dcode}, field: {rs_str(f.name)}, "
                       f"name: {rs_str(s.name)}, value: 0o{s.value:o} }},")
    out += ["];", "",
            "/// The value of a symbol of a microword field.",
            "pub fn symbol(field: &str, name: &str) -> Option<u32> {",
            "    SYMBOLS.iter().find(|s| !s.dcode && s.field == field && s.name == name).map(|s| s.value)",
            "}", "",
            "/// The address of a tag: a symbol of the microword field `J`.",
            "pub fn tag(name: &str) -> Option<u16> {",
            "    symbol(\"J\", name).and_then(|v| u16::try_from(v).ok())",
            "}", ""]
    return "\n".join(out)


def outputs(its_dir: Path) -> dict:
    try:
        a = micro.assemble(its_dir)
    except micro.MicroError as e:
        raise MicrocodeError(f"MICRO: {e}") from None
    return {OUT_RS: render_rust(a), OUT_UCODE: render_ucode(a)}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Generate the KS10 microword field tables.")
    ap.add_argument("--its", type=Path, required=True, help="the ITS tree")
    ap.add_argument("--check", action="store_true", help="compare only; write nothing")
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    args = ap.parse_args(argv)
    try:
        outs = outputs(args.its)
    except (MicrocodeError, its.SourceError) as e:
        print(f"ITS microcode: {e}", file=sys.stderr)
        return 1
    status = 0
    for rel, text in outs.items():
        path = args.root / rel
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f"{rel} is not current; run make gen", file=sys.stderr)
                status = 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_text() != text:
                path.write_text(text)
                print(f"wrote {rel}")
    return status


if __name__ == "__main__":
    sys.exit(main())
