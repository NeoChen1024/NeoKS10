#!/usr/bin/env python3
"""Generate the field tables of the KS10 microword from the ITS microcode.

The ITS KS10 microcode sources (src/kshack/ of the submodule 3rdparty/its)
are the first source of truth (AGENTS.md). This program reads from them:

  - The fields of the microword (the definitions "NAME/=<first:last>" in
    .UCODE mode). The bits have the numbers of MICRO: bit 0 is the left
    end of the 108-bit word (ks10, ".WIDTH/108").
  - The fields of the dispatch ROM word (the definitions in .DCODE mode).
  - The layout of the RAM file (ks10, ".RAMFILE"), which the 8080 loads
    into the control RAM. MICRO packs the listed items from left to right
    into 108 bits (micro, $RAMFL and RAMFL4). A number "n/0" or "0" is n
    or 1 bits of padding. "ODD PARITY<a:b,...>" is one bit: the XOR of the
    given bits of the RAM file entry; "EVEN PARITY" is its complement
    (micro, RAMFP1 and PNTB91).

Output (path relative to the repository root):
  emu/ks10-core-uop/src/fields.rs

Usage: gen_microcode.py --its DIR [--check] [--root DIR]
  --its DIR  the ITS tree (the submodule 3rdparty/its).
  --check    compare the output with the file on disk; write nothing.

Exit status 1 if a check fails. Only the Python standard library is used.
"""

import argparse
import re
import sys
from pathlib import Path

import its_sources as its

OUT_RS = "emu/ks10-core-uop/src/fields.rs"
HEADER = "Generated by spec/gen_microcode.py from the ITS microcode sources. Do not edit."
WIDTH = 108

FIELD_RE = re.compile(r"([A-Z#][A-Z0-9#. -]*?)/=<(\d+)(?::(\d+))?>")


class MicrocodeError(Exception):
    """The sources do not have the expected form."""


def read(ucode_dir: Path) -> dict:
    """Read the field definitions and the .RAMFILE text.

    The result has:
      ufields  [(name, first, last, "file:line")] of the microword, in the
               order of the source. A name has one definition.
      dfields  the same for the dispatch ROM word.
      ramfile  (text, "file:line") of the .RAMFILE directive.
    """
    ufields, dfields, seen = [], [], {"U": {}, "D": {}}
    ramfile = None
    pending = None
    for fname, n, mode, text, _ in its._active_lines(ucode_dir):
        where = f"{fname}:{n}"
        if pending is not None:
            pending[0] += " " + text.strip()
            if not text.strip().endswith(","):
                ramfile, pending = (pending[0], pending[1]), None
            continue
        t = text.strip()
        if t.startswith(".RAMFILE/"):
            if ramfile is not None:
                raise MicrocodeError(f"{where}: a second .RAMFILE")
            pending = [t[len(".RAMFILE/"):], where]
            if not t.endswith(","):
                ramfile, pending = (pending[0], pending[1]), None
            continue
        m = FIELD_RE.match(text)
        if not m:
            continue
        name = m.group(1).strip()
        first = int(m.group(2))
        last = int(m.group(3)) if m.group(3) else first
        if last < first:
            raise MicrocodeError(f"{where}: field {name} ends before it starts")
        if name in seen[mode]:
            prev = seen[mode][name]
            if prev[:2] != (first, last):
                raise MicrocodeError(f"{where}: field {name} redefined (first at {prev[2]})")
            continue
        seen[mode][name] = (first, last, where)
        (ufields if mode == "U" else dfields).append((name, first, last, where))
    if ramfile is None:
        raise MicrocodeError(f"{ucode_dir}: no .RAMFILE")
    return {"ufields": ufields, "dfields": dfields, "ramfile": ramfile}


def parse_ramfile(text: str, ufields: list) -> list:
    """The items of the RAM file, from left to right.

    Each item is ("field", name, first, width, dest), ("pad", width, dest)
    or ("parity", odd, ((first, last), ...), dest). dest is the first bit
    of the item in the RAM file entry; first is a microword bit.
    """
    defs = {name: (first, last) for name, first, last, _ in ufields}
    items, bit = [], 0
    # Split at the commas that are not inside <...>.
    tokens, depth, cur = [], 0, ""
    for c in text:
        if c == "<":
            depth += 1
        elif c == ">":
            depth -= 1
        if c == "," and depth == 0:
            tokens.append(cur.strip())
            cur = ""
        else:
            cur += c
    if cur.strip():
        tokens.append(cur.strip())
    for tok in tokens:
        tok = re.sub(r"\s+", " ", tok)
        m = re.fullmatch(r"(ODD|EVEN) PARITY<([\d:, ]+)>", tok)
        if m:
            ranges = []
            for r in m.group(2).split(","):
                a, b = (int(x) for x in r.split(":"))
                ranges.append((a, b))
            items.append(("parity", m.group(1) == "ODD", tuple(ranges), bit))
            bit += 1
            continue
        m = re.fullmatch(r"(?:(\d+)/)?0", tok)
        if m:
            width = int(m.group(1)) if m.group(1) else 1
            items.append(("pad", width, bit))
            bit += width
            continue
        if tok not in defs:
            raise MicrocodeError(f".RAMFILE: field {tok!r} is not defined")
        first, last = defs[tok]
        width = last - first + 1
        if bit // 36 != (bit + width - 1) // 36:
            raise MicrocodeError(f".RAMFILE: field {tok} crosses a word of the RAM file")
        items.append(("field", tok, first, width, bit))
        bit += width
    if bit != WIDTH:
        raise MicrocodeError(f".RAMFILE: {bit} bits, expected {WIDTH}")
    for item in items:
        if item[0] == "parity":
            for a, b in item[2]:
                if not 0 <= a <= b < WIDTH:
                    raise MicrocodeError(f".RAMFILE: parity range {a}:{b} outside the entry")
    return items


def rs_ident(name: str) -> str:
    s = name.upper().replace("#", "_NUM_")
    s = re.sub(r"[^A-Z0-9]+", "_", s).strip("_")
    return s


def render_rust(data: dict, items: list) -> str:
    out = [f"// {HEADER}", "",
           "//! The fields of the KS10 microword and of the dispatch ROM word, and the",
           "//! layout of the RAM file, from the ITS microcode sources",
           "//! **[microcode]** (`ks10`, `.WIDTH`, `.RAMFILE` and the field definitions).",
           "//! Bit 0 is the left end of a word, as in MICRO.", "",
           "/// A field: bits `first..=last` of a word, bit 0 at the left end.",
           "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
           "pub struct Field {",
           "    pub name: &'static str,",
           "    pub first: u8,",
           "    pub last: u8,",
           "}", "",
           "/// The width of a microword in bits (`.WIDTH/108`).",
           f"pub const WIDTH: u32 = {WIDTH};", ""]
    for kind, fields, doc in (("u", data["ufields"], "microword"), ("d", data["dfields"], "dispatch ROM word")):
        idents = {}
        out.append(f"/// The fields of the {doc}.")
        out.append(f"pub mod {kind} {{")
        out.append("    use super::Field;")
        for name, first, last, where in fields:
            ident = rs_ident(name)
            if ident in idents:
                raise MicrocodeError(f"fields {name!r} and {idents[ident]!r} have the same Rust name")
            idents[ident] = name
            out.append(f"    /// `{name}/=<{first}:{last}>` ({where}).")
            out.append(f"    pub const {ident}: Field = Field {{ name: \"{name}\", first: {first}, last: {last} }};")
        out.append("    /// All fields, in the order of the source.")
        out.append("    pub const ALL: &[Field] = &[")
        for name, *_ in fields:
            out.append(f"        {rs_ident(name)},")
        out.append("    ];")
        out.append("}")
        out.append("")
    out += ["/// An item of the RAM file entry, which is 108 bits in three 36-bit words.",
            "/// `dest` is the first bit of the item in the entry, bit 0 at the left end of",
            "/// the first word.",
            "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
            "pub enum RamItem {",
            "    /// A microword field.",
            "    Field { field: Field, dest: u8 },",
            "    /// Bits that are 0.",
            "    Pad { width: u8, dest: u8 },",
            "    /// One parity bit: the XOR of the entry bits in `ranges` (`odd`), or its",
            "    /// complement (`!odd`, \"EVEN PARITY\").",
            "    Parity { odd: bool, ranges: &'static [(u8, u8)], dest: u8 },",
            "}", "",
            f"/// The items of `.RAMFILE` ({data['ramfile'][1]}), from left to right.",
            "pub const RAMFILE: &[RamItem] = &["]
    for item in items:
        if item[0] == "field":
            _, name, _, _, dest = item
            out.append(f"    RamItem::Field {{ field: u::{rs_ident(name)}, dest: {dest} }},")
        elif item[0] == "pad":
            out.append(f"    RamItem::Pad {{ width: {item[1]}, dest: {item[2]} }},")
        else:
            ranges = ", ".join(f"({a}, {b})" for a, b in item[2])
            odd = "true" if item[1] else "false"
            out.append(f"    RamItem::Parity {{ odd: {odd}, ranges: &[{ranges}], dest: {item[3]} }},")
    out.append("];")
    out.append("")
    return "\n".join(out)


def outputs(its_dir: Path) -> dict:
    data = read(its_dir / "src" / "kshack")
    items = parse_ramfile(data["ramfile"][0], data["ufields"])
    return {OUT_RS: render_rust(data, items)}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Generate the KS10 microword field tables.")
    ap.add_argument("--its", type=Path, required=True, help="the ITS tree")
    ap.add_argument("--check", action="store_true", help="compare only; write nothing")
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    args = ap.parse_args(argv)
    try:
        outs = outputs(args.its)
    except (MicrocodeError, its.SourceError) as e:
        print(f"ITS microcode: {e}", file=sys.stderr)
        return 1
    status = 0
    for rel, text in outs.items():
        path = args.root / rel
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f"{rel} is not current; run make gen", file=sys.stderr)
                status = 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_text() != text:
                path.write_text(text)
                print(f"wrote {rel}")
    return status


if __name__ == "__main__":
    sys.exit(main())
