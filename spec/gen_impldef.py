#!/usr/bin/env python3
"""Check the table of implementation differences and write its document.

Source: spec/impldef.toml. Output (path relative to the repository root):
  docs/impldef.md   the table, the sources of each case, and the programs

The check: each case names its section of docs/discrepancies.md, its item
of docs/unknowns.md or its entry of docs/emulator.md; its instructions are
in spec/instructions.toml; its predicate is in PREDICATES; a case of level
B gives the reason for the level; a case where ks10-core-uop and
ks10-core-soft differ has level B or the state open (docs/conformance.md).

Usage: gen_impldef.py [--check] [--root DIR]
  --check  compare the output with the file on disk; write nothing.

Exit status 1 if a check fails. Only the Python standard library is used.
"""

import argparse
import re
import sys
import tomllib
from pathlib import Path

SOURCE = "spec/impldef.toml"
OUT_MD = "docs/impldef.md"
HEADER = f"<!-- Generated by spec/gen_impldef.py from {SOURCE}. Do not edit. -->"

# The predicates of `when`: name -> (parameters, text for the document).
# A parameter "*instruction" takes one value for each instruction of the case.
PREDICATES = {
    "any": ([], "every case of the instructions"),
    "left_shift_over": (["*instruction"], "a left shift by more places than the value for the instruction"),
    "count_minus_256": ([], "E with bit 18 set and bits 28 to 35 clear: a count of -256"),
    "imul_negative_product_over_word": ([], "a negative product of magnitude 2^35 + 1 to 2^36 - 1"),
    "idiv_min_by_unit": ([], "a dividend of -2^35 and a divisor of 1 or -1"),
    "div_min70_by_zero": ([], "a dividend of -2^70 and a divisor of 0"),
    "hlle_positive_bits_1_3": ([], "a positive source word with a bit of 1 to 3 set"),
    "div_high_equals_divisor": ([], "the high word of the magnitude of the dividend equals the magnitude of the divisor"),
    "start_flags": (["flags"], "an instruction of the case that starts with one of the flags set"),
    "lost_bit_before_last_step": ([], "a left shift that loses a bit in a step before the last step, and none in the last step"),
    "exponent_difference_over": (["n"], "an exponent difference of more than n"),
    "unnormalized_operand": ([], "an operand that is not normalized"),
    "page_fail": ([], "a reference that page-fails"),
}
FLAGS = {"AROV", "CRY0", "CRY1", "FOV", "FPD", "USER", "USERIO", "TRAP1", "TRAP2", "FXU", "NODIV"}
MARKS = {"microcode", "its", "manual", "emulator", "measured", "estimate"}
LEVELS = {"A", "B", "open"}
STATES = {"open", "decided", "confirmed"}
AREAS = {"processor": ("uop", "soft", "pipelined"), "device": ("machine",)}
RUNS = ("simh", "klh10", "uop_soft")
COMPARE = {"exact", "mask", "skip", "not-generated"}
NAME = re.compile(r"[a-z][a-z0-9-]*")
DIFFERS = re.compile(r"(ac|mem|pc|register|flags:[A-Z0-9]+(,[A-Z0-9]+)*|pfw:\d+-\d+)")
ORIGINS = {
    "discrepancy": "docs/discrepancies.md",
    "unknown": "docs/unknowns.md",
    "difference": "docs/emulator.md",
}


class ImpldefError(Exception):
    """spec/impldef.toml does not have the expected form."""


def mnemonics(root: Path) -> set:
    data = tomllib.loads((root / "spec/instructions.toml").read_text())
    names = {o["name"] for o in data["op"]} | {a["name"] for a in data["acdisp"]}
    return names - {""}


def check_case(c: dict, docs: dict, names: set) -> None:
    n = c.get("name", "")
    where = f"case {n!r}"
    if not NAME.fullmatch(n):
        raise ImpldefError(f"{where}: the name is not valid")
    for key in ("title", "area", "level", "state", "sources", "choice", "program"):
        if key not in c:
            raise ImpldefError(f"{where}: no {key!r}")
    origins = [k for k in ORIGINS if k in c]
    if len(origins) != 1:
        raise ImpldefError(f"{where}: give one of {', '.join(ORIGINS)}")
    o = origins[0]
    text = c[o]
    found = f"## {text}\n" in docs[o] if o == "discrepancy" else text in docs[o]
    if not found:
        raise ImpldefError(f"{where}: {ORIGINS[o]} has no {text!r}")
    if c["area"] not in AREAS:
        raise ImpldefError(f"{where}: area {c['area']!r}")
    if c["level"] not in LEVELS:
        raise ImpldefError(f"{where}: level {c['level']!r}")
    if (c["level"] == "B") != ("level_b" in c):
        raise ImpldefError(f"{where}: level_b is for level B only, and level B needs it")
    if c["state"] not in STATES:
        raise ImpldefError(f"{where}: state {c['state']!r}")
    for d in c.get("differs", []):
        if not DIFFERS.fullmatch(d):
            raise ImpldefError(f"{where}: differs {d!r}")
        if d.startswith("flags:") and not set(d[6:].split(",")) <= FLAGS:
            raise ImpldefError(f"{where}: unknown flag in {d!r}")
    for s in c["sources"]:
        if set(s) != {"who", "mark", "ref", "does"}:
            raise ImpldefError(f"{where}: a source needs who, mark, ref and does")
        if s["mark"] not in MARKS:
            raise ImpldefError(f"{where}: mark {s['mark']!r}")
        if re.search(r"M86\d\d-", s["ref"]) and " rev " not in s["ref"]:
            raise ImpldefError(f"{where}: a drawing needs its revision: {s['ref']!r}")
    if len(c["sources"]) < 2:
        raise ImpldefError(f"{where}: a case needs two sources that differ")
    if set(c["choice"]) != set(AREAS[c["area"]]):
        raise ImpldefError(f"{where}: choice needs {', '.join(AREAS[c['area']])}")
    if c["area"] == "processor":
        ins = c.get("instructions", [])
        if not ins or not set(ins) <= names:
            raise ImpldefError(f"{where}: instructions {sorted(set(ins) - names)} not in spec/instructions.toml")
        pred = c.get("when", {}).get("pred")
        if pred not in PREDICATES:
            raise ImpldefError(f"{where}: predicate {pred!r}")
        params = set(c["when"]) - {"pred"}
        want = PREDICATES[pred][0]
        if want == ["*instruction"]:
            want = ins
        if params != set(want):
            raise ImpldefError(f"{where}: {pred} needs {want}")
        if "flags" in params and not set(c["when"]["flags"]) <= FLAGS:
            raise ImpldefError(f"{where}: unknown flag in when")
        cmp = c.get("compare", {})
        if set(cmp) != set(RUNS) or not set(cmp.values()) <= COMPARE:
            raise ImpldefError(f"{where}: compare needs {', '.join(RUNS)} with {sorted(COMPARE)}")
        if "mask" in cmp.values() and not c.get("differs"):
            raise ImpldefError(f"{where}: a mask needs differs")
        # docs/conformance.md: each difference between the two models is a
        # case of level B (or an item of level C, which is not a case).
        ch = c["choice"]
        differ = cmp.get("uop_soft") == "mask" or (
            "open" not in (ch["uop"], ch["soft"]) and ch["uop"] != ch["soft"])
        if differ and c["level"] != "B" and c["state"] != "open":
            raise ImpldefError(f"{where}: uop and soft differ, so level B or state open")
    elif "instructions" in c or "compare" in c:
        raise ImpldefError(f"{where}: a device case has no instructions or compare")


def load(root: Path) -> list:
    data = tomllib.loads((root / SOURCE).read_text())
    if data.get("format") != 1:
        raise ImpldefError("format must be 1")
    cases = data.get("case", [])
    docs = {k: (root / p).read_text() for k, p in ORIGINS.items()}
    names = mnemonics(root)
    seen = set()
    for c in cases:
        check_case(c, docs, names)
        if c["name"] in seen:
            raise ImpldefError(f"case {c['name']!r} is not unique")
        seen.add(c["name"])
    return cases


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def render(cases: list) -> str:
    proc = [c for c in cases if c["area"] == "processor"]
    dev = [c for c in cases if c["area"] == "device"]
    out = [HEADER, "", "# Implementation differences", "",
           "Each case is a behaviour in which the implementations of the KS10 differ.",
           "The levels A, B and open and the rules for them are in",
           "[`conformance.md`](conformance.md). The sources of each case are in",
           "[`discrepancies.md`](discrepancies.md), [`unknowns.md`](unknowns.md) or",
           "[`emulator.md`](emulator.md).", "",
           "Columns: the choice of `ks10-core-uop` (uop), `ks10-core-soft` (soft) and",
           "the pipelined core, and the comparison in each differential run. A",
           "comparison is exact, mask (the differing fields are not compared), skip",
           "(the case is not compared) or not-generated (the run makes no such case).",
           "The programs are not assembled or run yet.",
           "", "## Processor", "",
           "| Case | Level | State | uop | soft | pipelined | SIMH | KLH10 | uop/soft |",
           "|---|---|---|---|---|---|---|---|---|"]
    for c in proc:
        ch, cm = c["choice"], c["compare"]
        out.append(f"| [{c['name']}](#{c['name']}) | {c['level']} | {c['state']} | "
                   f"{cell(ch['uop'])} | {cell(ch['soft'])} | {cell(ch['pipelined'])} | "
                   f"{cm['simh']} | {cm['klh10']} | {cm['uop_soft']} |")
    out += ["", "## Devices", "", "| Case | Level | State | ks10-machine |", "|---|---|---|---|"]
    for c in dev:
        out.append(f"| [{c['name']}](#{c['name']}) | {c['level']} | {c['state']} | "
                   f"{cell(c['choice']['machine'])} |")
    out += ["", "## Predicates", "",
            "The operands of a case (`when` in the table):", ""]
    for p, (_, text) in PREDICATES.items():
        out.append(f"- `{p}`: {text}.")
    out += ["", "## Cases", ""]
    for c in cases:
        out += [f"### {c['name']}", "", f"{c['title']}.", ""]
        if c["area"] == "processor":
            w = dict(c["when"])
            pred = w.pop("pred")
            args = ", ".join(f"{k} {v}" for k, v in w.items())
            out.append(f"- Instructions: {', '.join(c['instructions'])}; operands: `{pred}`"
                       + (f" ({args})" if args else "") + ".")
        if c.get("differs"):
            out.append(f"- Differs: {', '.join(c['differs'])}.")
        if "level_b" in c:
            out.append(f"- Level B: {c['level_b']}")
        o = next(k for k in ORIGINS if k in c)
        out.append(f"- Origin: [`{Path(ORIGINS[o]).name}`]({Path(ORIGINS[o]).name}), \"{c[o]}\".")
        out += ["", "Sources:", ""]
        for s in c["sources"]:
            out.append(f"- {s['who']} **[{s['mark']}]** ({s['ref']}): {s['does']}.")
        if "note" in c:
            out += ["", c["note"]]
        out += ["", "Program:", "", "```", c["program"].strip("\n"), "```", ""]
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Check spec/impldef.toml and write docs/impldef.md.")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=Path(__file__).resolve().parent.parent, type=Path)
    a = ap.parse_args(argv)
    try:
        text = render(load(a.root))
    except ImpldefError as e:
        print(f"{SOURCE}: {e}", file=sys.stderr)
        return 1
    p = a.root / OUT_MD
    if a.check:
        if not p.exists() or p.read_text() != text:
            print(f"{OUT_MD} is not current: run make gen", file=sys.stderr)
            return 1
        return 0
    p.write_text(text)
    print(f"wrote {OUT_MD}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
