#!/usr/bin/env python3
"""Generate the C interface files of the microcode-level model.

Source: spec/capi.toml. Output (paths relative to the repository root):
  tb/gen/ks10_capi.h        the C header
  emu/ks10-capi/src/capi.rs  the record, the status codes, and a function
                            pointer type for each function

The crate emu/ks10-capi assigns each of its functions to the pointer type
of capi.rs, so a function that differs from spec/capi.toml does not
compile, and the header has the same declarations.

Usage: gen_capi.py [--check] [--root DIR]
  --check  compare the outputs with the files on disk; write nothing.

Exit status 1 if a check fails. Only the Python standard library is used.
"""

import argparse
import re
import sys
import tomllib
from pathlib import Path

SOURCE = "spec/capi.toml"
OUT_H = "tb/gen/ks10_capi.h"
OUT_RS = "emu/ks10-capi/src/capi.rs"
HEADER = f"Generated by spec/gen_capi.py from {SOURCE}. Do not edit."

# C type -> Rust type.
TYPES = {
    "void": "()",
    "int": "c_int",
    "uint32_t": "u32",
    "uint64_t": "u64",
    "size_t": "usize",
    "uint64_t *": "*mut u64",
    "char *": "*mut c_char",
    "ks10_uop *": "*mut Ks10Uop",
    "const ks10_uop *": "*const Ks10Uop",
    "ks10_record *": "*mut Ks10Record",
}
NAME = re.compile(r"[a-z][a-z0-9_]*")


class CapiError(Exception):
    """spec/capi.toml does not have the expected form."""


def load(path: Path) -> dict:
    data = tomllib.loads(path.read_text())
    if data.get("prefix") != "ks10":
        raise CapiError("prefix must be ks10")
    names = set()
    for s in data["status"]:
        if not re.fullmatch(r"[A-Z][A-Z0-9_]*", s["name"]) or not isinstance(s["value"], int):
            raise CapiError(f"status {s!r}")
    values = [s["value"] for s in data["status"]]
    if len(set(values)) != len(values) or 0 not in values:
        raise CapiError("status values must differ, and 0 must be one of them")
    for r in data["record"]:
        if not NAME.fullmatch(r["name"]) or r["name"] in names:
            raise CapiError(f"record field {r['name']!r}")
        names.add(r["name"])
        if r.get("count", 1) < 1:
            raise CapiError(f"record field {r['name']}: count")
    fnames = set()
    for f in data["function"]:
        if not NAME.fullmatch(f["name"]) or f["name"] in fnames:
            raise CapiError(f"function {f['name']!r}")
        fnames.add(f["name"])
        for t in [f["returns"]] + [a[0] for a in f["args"]]:
            if t not in TYPES:
                raise CapiError(f"function {f['name']}: type {t!r}")
        for _, n in f["args"]:
            if not NAME.fullmatch(n):
                raise CapiError(f"function {f['name']}: argument {n!r}")
    return data


def c_decl(t: str, name: str) -> str:
    return f"{t}{name}" if t.endswith("*") else f"{t} {name}"


def camel(name: str) -> str:
    return "".join(p.capitalize() for p in name.split("_"))


def render_h(data: dict) -> str:
    out = [f"/* {HEADER} */", "#ifndef NEOKS10_KS10_CAPI_H", "#define NEOKS10_KS10_CAPI_H", "",
           "#include <stddef.h>", "#include <stdint.h>", "",
           "#ifdef __cplusplus", 'extern "C" {', "#endif", "",
           "/* A microcode-level model (emu/ks10-capi). */",
           "typedef struct ks10_uop ks10_uop;", ""]
    for s in data["status"]:
        out.append(f"/* {s['doc']} */")
        out.append(f"#define KS10_{s['name']} ({s['value']})")
    out += ["", "/* The record of a completed instruction (docs/microcode-model.md). */",
            "typedef struct ks10_record {"]
    for r in data["record"]:
        n = r.get("count", 1)
        dim = f"[{n}]" if n > 1 else ""
        out.append(f"    /* {r['doc']} */")
        out.append(f"    uint64_t {r['name']}{dim};")
    out += ["} ks10_record;", ""]
    for f in data["function"]:
        args = ", ".join(c_decl(t, n) for t, n in f["args"]) or "void"
        out.append(f"/* {f['doc']} */")
        out.append(f"{c_decl(f['returns'], 'ks10_' + f['name'])}({args});")
    out += ["", "#ifdef __cplusplus", "}", "#endif", "", "#endif", ""]
    return "\n".join(out)


def render_rs(data: dict) -> str:
    out = [f"// {HEADER}", "",
           "//! The record, the status codes and the function types of the C",
           "//! interface (spec/capi.toml).", "",
           "use std::ffi::{c_char, c_int};", "",
           "use crate::Ks10Uop;", ""]
    for s in data["status"]:
        out.append(f"/// {s['doc']}")
        out.append(f"pub const KS10_{s['name']}: c_int = {s['value']};")
    out += ["", "/// The record of a completed instruction (`ks10_record`).",
            "#[repr(C)]", "#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]",
            "pub struct Ks10Record {"]
    for r in data["record"]:
        n = r.get("count", 1)
        t = f"[u64; {n}]" if n > 1 else "u64"
        out.append(f"    /// {r['doc']}")
        out.append(f"    pub {r['name']}: {t},")
    out += ["}", ""]
    for f in data["function"]:
        args = ", ".join(TYPES[t] for t, _ in f["args"])
        ret = "" if f["returns"] == "void" else f" -> {TYPES[f['returns']]}"
        out.append(f"/// `ks10_{f['name']}`.")
        out.append(f"pub type {camel(f['name'])} = unsafe extern \"C\" fn({args}){ret};")
    out.append("")
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Generate the C interface files.")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    args = ap.parse_args(argv)
    try:
        data = load(args.root / SOURCE)
    except (CapiError, KeyError, tomllib.TOMLDecodeError) as e:
        print(f"{SOURCE}: {e}", file=sys.stderr)
        return 1
    status = 0
    for rel, text in {OUT_H: render_h(data), OUT_RS: render_rs(data)}.items():
        p = args.root / rel
        if args.check:
            if not p.exists() or p.read_text() != text:
                print(f"{rel} is not current; run make gen", file=sys.stderr)
                status = 1
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
            print(f"wrote {rel}")
    return status


if __name__ == "__main__":
    sys.exit(main())
